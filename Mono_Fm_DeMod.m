% Mono_Fm_DeMod.m
% FM Receiver for Mono Audio Stream with Diagnostic Visualizations

clear; clc; close all;

%% 1. File Configuration & Length Calculation
fs2 = 1e6;       % USRP sampling rate (1 MHz)
f_delta = 75e3;  % Frequency deviation used in transmitter

% Choose which file to read:
% Option A: 'tx_mono.bin' (your synthesized file)
% Option B: 'rx_data_4MSamples1MsPs_97.8MHz.bin' (the commercial recording)
input_filename = 'tx_mono.bin';

% Dynamically calculate the number of samples (data_len)
file_info = dir(input_filename);
if isempty(file_info)
    error('File not found. Please ensure %s is in the current folder.', input_filename);
end

% 1 double = 8 bytes. 1 complex number (Real + Imag) = 16 bytes.
data_len = file_info.bytes / 16;

%% 2. Read the modulated data using the lab's exact function
try
    % Pass both the filename and the calculated data length
    y_rx = RD_bin_file(input_filename, data_len);
catch
    warning('RD_bin_file.m not found or failed. Generating synthetic mock data for visual fallback.');
    % Fallback mock data if running outside of the physical lab folder
    t_mock = (0:data_len-1)' / fs2;
    % Synthetic modulated FM wave carrying a 1 kHz tone
    y_rx = exp(1i * 2 * pi * 100e3 * t_mock + 1i * (75e3/1e3) * sin(2 * pi * 1e3 * t_mock));
end

% Ensure column vector format for easier processing
y_rx = y_rx(:);

%% 3. Demodulate the signal manually (Phase Discriminator)
phase_y = unwrap(angle(y_rx)); % Extract and unwrap the phase

% Differentiate the phase to recover the original message signal
x_demod = diff(phase_y) * (fs2 / (2 * pi * f_delta));
x_demod = [x_demod; x_demod(end)]; % Restore original length

%% 4. Discard initial samples to remove filter and buffer transients
discard_len = round(0.1 * fs2); % Discard first 0.1 seconds
x_demod_clean = x_demod(discard_len:end);

%% 5. Filter and Down-sample back to audio frequencies
% Down-sample from 1 MHz back to 200 kHz
fs1 = 200e3;
x_down1 = resample(x_demod_clean, fs1, fs2);

% Low-pass filter at 15 kHz to remove high-frequency noise generated by differentiation
f_cutoff = 15e3;
[b, a] = butter(6, f_cutoff / (fs1 / 2), 'low');
x_audio_baseband = filtfilt(b, a, x_down1);

% Down-sample to a standard audio rate (e.g., 44.1 kHz) to play on PC
fs_audio_out = 44100;
x_audio_final = resample(x_audio_baseband, fs_audio_out, fs1);

% Normalize audio for playback to avoid clipping distortion
x_audio_final = x_audio_final / (max(abs(x_audio_final)) + 1e-10);

%% 6. Generate Diagnostic Plots (3x2 Grid Tracking Demodulation)
% Create continuous time vectors representing the duration in seconds
t_rx_axis     = (0 : length(y_rx)-1)' / fs2;
t_down_axis  = (0 : length(x_down1)-1)' / fs1;
t_audio_axis = (0 : length(x_audio_final)-1)' / fs_audio_out;

% Compute FFT of Raw Received Signal (Stage 1)
% Limit points dynamically to prevent slowdowns on massive files
N_rx_points = min(length(y_rx), 1e6);
X_rx_fft = fftshift(fft(y_rx(1:N_rx_points)));
f_rx_axis = (-N_rx_points/2 : N_rx_points/2-1) * (fs2 / N_rx_points);

% Compute FFT of Downsampled Signal before LPF (Stage 2)
N_down_points = min(length(x_down1), 1e6);
X_down_fft = fftshift(fft(x_down1(1:N_down_points)));
f_down_axis = (-N_down_points/2 : N_down_points/2-1) * (fs1 / N_down_points);

% Compute FFT of Final Recovered Audio (Stage 3)
N_audio_points = min(length(x_audio_final), 1e6);
X_audio_fft = fftshift(fft(x_audio_final(1:N_audio_points)));
f_audio_axis = (-N_audio_points/2 : N_audio_points/2-1) * (fs_audio_out / N_audio_points);

% Create the 3x2 Diagnostic Figure
figure('Name', 'FM Demodulator Analysis: Processing Stages', 'NumberTitle', 'off');

% Subplot 1: Received Signal (Time Domain - Real Part)
subplot(3, 2, 1);
plot(t_rx_axis, real(y_rx), 'g', 'LineWidth', 0.5);
title('Received Signal (Time Domain - Real Part)');
xlabel('Time (seconds)');
ylabel('Amplitude');
xlim([0 t_rx_axis(end)]);
grid on;

% Subplot 2: Received Signal (Frequency Domain)
subplot(3, 2, 2);
plot(f_rx_axis / 1e3, 20*log10(abs(X_rx_fft) + 1e-10), 'g');
title('Received Signal (Frequency Domain)');
xlabel('Frequency (kHz)');
ylabel('Magnitude (dB)');
xlim([-fs2/(2*1e3) fs2/(2*1e3)]); % Show complete Nyquist space (±500 kHz)
grid on;

% Subplot 3: Downsampled to 200 kHz - Pre-filter (Time Domain)
subplot(3, 2, 3);
plot(t_down_axis, x_down1, 'r', 'LineWidth', 0.5);
title('Downsampled 200 kHz Signal (Time Domain)');
xlabel('Time (seconds)');
ylabel('Amplitude');
xlim([0 t_down_axis(end)]);
grid on;

% Subplot 4: Downsampled to 200 kHz - Pre-filter (Frequency Domain)
subplot(3, 2, 4);
plot(f_down_axis / 1e3, 20*log10(abs(X_down_fft) + 1e-10), 'r');
title('Downsampled 200 kHz Signal (Frequency Domain)');
xlabel('Frequency (kHz)');
ylabel('Magnitude (dB)');
xlim([-fs1/(2*1e3) fs1/(2*1e3)]); % Show decimated bandwidth (±100 kHz)
grid on;

% Subplot 5: Final Filtered Audio (Time Domain)
subplot(3, 2, 5);
plot(t_audio_axis, x_audio_final, 'b', 'LineWidth', 0.8);
title('Final Demodulated Audio (Time Domain)');
xlabel('Time (seconds)');
ylabel('Normalized Amplitude');
xlim([0 t_audio_axis(end)]);
grid on;

% Subplot 6: Final Filtered Audio (Frequency Domain)
subplot(3, 2, 6);
plot(f_audio_axis / 1e3, 20*log10(abs(X_audio_fft) + 1e-10), 'b');
title('Final Demodulated Audio (Frequency Domain)');
xlabel('Frequency (kHz)');
ylabel('Magnitude (dB)');
xlim([-fs_audio_out/(2*1e3) fs_audio_out/(2*1e3)]); % Show audio band (±22.05 kHz)
xline(15, '--k', '15 kHz Audio Limit', 'LabelHorizontalAlignment', 'right');
xline(-15, '--k');
grid on;

%% 7. Play back the audio
disp('Playing demodulated audio...');
soundsc(x_audio_final, fs_audio_out);

%% 8. Optional: Compare against Original File (Robust Wrapper)
original_file = 'piano2.wav';
if exist(original_file, 'file')
    [original_audio, fs_orig] = audioread(original_file);
    if size(original_audio, 2) > 1
        original_audio = mean(original_audio, 2);
    end
    original_audio = resample(original_audio, fs_audio_out, fs_orig);

    % Execute helper functions if they exist in the workspace
    if exist('plot_visual_comparison', 'file')
        plot_visual_comparison(original_audio, x_audio_final, fs_audio_out);
    end
    if exist('calc_numerical_comparison', 'file')
        calc_numerical_comparison(original_audio, x_audio_final);
    end
end